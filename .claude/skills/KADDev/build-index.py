#!/usr/bin/env python3
"""Rebuild references/INDEX.md: for every reference file its size and, for each `##` section, the line it starts on plus its first sentence.
Why: SKILL.md (about 26 KB) and the references (about 280 KB) were read in full at the start of tasks. With the index a task reads
SKILL.md + INDEX.md (about 15 KB), then opens only the sections it needs (Read with offset/limit = the line numbers below).
Run after editing any reference:  python3 .claude/skills/KADDev/build-index.py   (idempotent; CI does not need it)."""
import re, sys
from pathlib import Path

root = Path(__file__).resolve().parent
refs = sorted((root / "references").glob("*.md"))
refs = [p for p in refs if p.name != "INDEX.md"]

def first_sentence(lines, start):
    text = ""
    for ln in lines[start + 1:start + 8]:
        t = ln.strip()
        if not t or t.startswith(("#", "|", "```", "---")):
            if text:
                break
            continue
        text += (" " if text else "") + re.sub(r"[*`_]", "", t.lstrip("-•0123456789. "))
        if re.search(r"[.!?:;]\s*$", text) or len(text) > 110:
            break
    text = re.sub(r"\s+", " ", text)
    m = re.match(r"(.{20,110}?[.!?])(\s|$)", text)
    return (m.group(1) if m else text[:110]).strip()

out = ["# Index of the references (generated by build-index.py: do not edit by hand)", "",
       "Read this, then open ONLY the sections the task needs: `Read file offset=<line> limit=<about 60>`. Line numbers shift when a file is edited:",
       "rebuild with `python3 .claude/skills/KADDev/build-index.py` after changing a reference.", ""]
for p in refs:
    lines = p.read_text(encoding="utf-8").split("\n")
    out.append(f"## {p.name} ({p.stat().st_size // 1024} KB, {len(lines)} lines)")
    for i, ln in enumerate(lines):
        m = re.match(r"^(##)\s+(.*)", ln)
        if m:
            s = first_sentence(lines, i)
            out.append(f"- L{i + 1} {m.group(2).strip()[:80]}" + (f" - {s}" if s else ""))
    out.append("")
(root / "references" / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
print(f"wrote references/INDEX.md ({sum(len(x) for x in out) // 1024} KB for {len(refs)} files)")
